#lo basico, suma y resta +, -

suma = 12 + 5
resta = 10 -5

#multiplicaciones y divisiones

multi = 15 * 5
division = 50 / 5 #por usar / devolverá un valor float

#potenciacion (exponente) **

exponente = 10 ** 5

#division baja //, devuelve enteros redondeados hacia abajo

div_baja = 10 // 5

#resto o modulo %, muestra unicamente el resto de una division

resto = 10 % 5

print(f"suma: {suma}\n"
      f"resta: {resta}\n"
      f"multiplicacion: {multi}\n"
      f"division: {division}\n"
      f"potenciacion: {exponente}\n"
      f"division baja: {div_baja}\n"
      f"resto: {resto}")

#type() para saber que tipo de dato es

print(type(div_baja))
